def build_system_prompt(job_title: str, tone: str | None, length: str | None) -> str:
    """직무와 화면에서 고른 값으로 시스템 프롬프트를 조립한다.
    """
    return " ".join(
        [
            BASE_PROMPT,
            f"지원 직무는 '{job_title}' 입니다.",
        ]
    )